// Project media for the PROJECTS window: Yeray's screenshots, the Capyroad video and this
// portfolio's own picture (made by `npm run share`), made light.
// These are NOT pixel art: they are shown crisp, as "a screen inside the screen" (DESIGN.md, "Content windows").
//
//   node scripts/media.mjs   → src/assets/projects/*.webp|mp4|webm + media.gen.ts
//   Exits with an error when a video is over the 2 MB budget.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './sprites/lib.mjs';

const SRC = join(ROOT, 'media-src/projects');
const OUT = join(ROOT, 'src/assets/projects');
const VIDEO_BUDGET = 2 * 1024 * 1024;

// Screenshots: two widths each, so phones download the small one (srcset).
const SCREENSHOTS = ['capyroad', 'pakitos-ruleta', 'pakitos-blackjack', 'portfolio'];
const WIDTHS = [640, 1280];

// The Capyroad video: only the app (the recording also shows the browser's tabs, bookmarks and
// sidebar, which are private), seconds 11–25: a crossing, the cash-out, "¡¡¡Has ganado!!!", a
// new round, the crash and "Has perdido :/" — both endings of "Cruzar o Cobrar".
const VIDEO = { name: 'capyroad', file: 'capyroad-raw.mp4', crop: '1810:830:70:114', start: 11, seconds: 14, width: 1280 };

const run = (args) => execFileSync('ffmpeg', ['-v', 'error', '-y', ...args]);
const kb = (path) => statSync(path).size / 1024;
const size = (path) =>
  execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', path]).toString().trim().split(',').map(Number);

mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) if (/\.(webp|mp4|webm)$/.test(f) || f === 'media.gen.ts') rmSync(join(OUT, f));

const lines = [];
let overBudget = false;

for (const name of SCREENSHOTS) {
  const [w, h] = size(join(SRC, `${name}.png`));
  for (const width of WIDTHS) {
    const out = join(OUT, `${name}-${width}.webp`);
    run(['-i', join(SRC, `${name}.png`), '-vf', `scale=${width}:-2:flags=lanczos`, '-c:v', 'libwebp', '-quality', '82', '-compression_level', '6', out]);
    console.log(`${name}-${width}.webp  ${kb(out).toFixed(0)} KB`);
  }
  lines.push({ name, width: w, height: h });
}

const clip = ['-ss', String(VIDEO.start), '-t', String(VIDEO.seconds), '-i', join(SRC, VIDEO.file)];
const look = `crop=${VIDEO.crop},scale=${VIDEO.width}:-2:flags=lanczos,fps=30`;
const mp4 = join(OUT, `${VIDEO.name}.mp4`);
const webm = join(OUT, `${VIDEO.name}.webm`);
const poster = join(OUT, `${VIDEO.name}-poster.webp`);
// H.264 for every browser, VP9 (smaller) for those that take it. No audio track.
run([...clip, '-vf', look, '-an', '-c:v', 'libx264', '-preset', 'slow', '-crf', '28', '-profile:v', 'high', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', mp4]);
run([...clip, '-vf', look, '-an', '-c:v', 'libvpx-vp9', '-crf', '38', '-b:v', '0', '-row-mt', '1', '-deadline', 'good', '-cpu-used', '2', webm]);
// The poster is the video's first frame, so starting playback does not jump.
run(['-ss', String(VIDEO.start), '-i', join(SRC, VIDEO.file), '-frames:v', '1', '-vf', `crop=${VIDEO.crop},scale=${VIDEO.width}:-2:flags=lanczos`, '-c:v', 'libwebp', '-quality', '80', poster]);
const [vw, vh] = size(mp4);
for (const file of [mp4, webm]) {
  const over = statSync(file).size > VIDEO_BUDGET;
  if (over) overBudget = true;
  console.log(`${file.split('/').pop()}  ${vw}×${vh}, ${VIDEO.seconds} s, ${kb(file).toFixed(0)} KB ${over ? '✗ over 2 MB' : '✓'}`);
}
console.log(`${VIDEO.name}-poster.webp  ${kb(poster).toFixed(0)} KB`);

const id = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const ts = [
  '// GENERATED by scripts/media.mjs — do not edit by hand.',
  '// Project screenshots (two widths) and the Capyroad video. Sizes in pixels.',
  ...lines.flatMap((l) => WIDTHS.map((w) => `import ${id(l.name)}${w} from './${l.name}-${w}.webp';`)),
  `import ${id(VIDEO.name)}Mp4 from './${VIDEO.name}.mp4';`,
  `import ${id(VIDEO.name)}Webm from './${VIDEO.name}.webm';`,
  `import ${id(VIDEO.name)}Poster from './${VIDEO.name}-poster.webp';`,
  '',
  'export type Screenshot = { small: string; large: string; width: number; height: number };',
  'export type Video = { mp4: string; webm: string; poster: string; width: number; height: number };',
  '',
  'export const SCREENSHOTS = {',
  ...lines.map((l) => `  ${id(l.name)}: { small: ${id(l.name)}${WIDTHS[0]}, large: ${id(l.name)}${WIDTHS[1]}, width: ${l.width}, height: ${l.height} },`),
  '} satisfies Record<string, Screenshot>;',
  '',
  `export const CAPYROAD_VIDEO: Video = { mp4: ${id(VIDEO.name)}Mp4, webm: ${id(VIDEO.name)}Webm, poster: ${id(VIDEO.name)}Poster, width: ${vw}, height: ${vh} };`,
  '',
];
writeFileSync(join(OUT, 'media.gen.ts'), ts.join('\n'));
console.log('→ src/assets/projects/ + media.gen.ts');
if (overBudget) process.exit(1);
