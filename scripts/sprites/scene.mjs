// Scene backgrounds: Yeray's generated images, used AS THEY ARE (same pixels, same size), only
// re-encoded as WebP so they weigh a tenth. The script also measures the image's pixel grid and
// reports it.
//
// Why not rebuild them on their native grid like the characters? The camp image has a clear 5.74 px
// grid, but it also draws details at half a pixel (outlines, highlights, the tripod's legs, the
// tent's rope). Snapped to its grid (239×133) those details turned into blobs and dotted lines;
// the original keeps them (docs/sprites.md, "Scenes").
//
//   node scripts/sprites/scene.mjs   → src/assets/scenes/*.webp + scenes.gen.ts
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REFS, ROOT, loadImage } from './lib.mjs';

const OUT_DIR = join(ROOT, 'src/assets/scenes');

// name → reference (relative to references/), its art-pixel size, and the WebP quality (85 looks
// the same as the original even at 2× zoom).
const SCENES = [{ name: 'camp', file: 'grandes/campamento.jpg', pitch: 5.74, quality: 85 }];

const diff = (a, b) => Math.abs(a[0] - b[0]) + Math.abs(a[1] - b[1]) + Math.abs(a[2] - b[2]);

/** How regular the image's pixel grid is at `pitch`: 0 = none, 1 = perfect (Yeray's front: 0.73). */
function gridScore(img, pitch) {
  const { w, h, at } = img;
  let re = 0, im = 0, total = 0;
  for (let y = 0; y < h; y += 2) {
    for (let x = 0; x < w - 1; x++) {
      if (diff(at(x, y), at(x + 1, y)) <= 40) continue;
      const angle = (2 * Math.PI * (x + 1)) / pitch; // the jump sits on the boundary x + 1
      re += Math.cos(angle);
      im += Math.sin(angle);
      total++;
    }
  }
  return total ? Math.hypot(re, im) / total : 0;
}

mkdirSync(OUT_DIR, { recursive: true });
for (const f of readdirSync(OUT_DIR)) if (/\.(png|webp)$/.test(f) || f === 'scenes.gen.ts') rmSync(join(OUT_DIR, f));

const entries = [];
for (const scene of SCENES) {
  const img = loadImage(scene.file);
  const out = join(OUT_DIR, `${scene.name}.webp`);
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', join(REFS, scene.file), '-c:v', 'libwebp', '-quality', String(scene.quality), '-compression_level', '6', out]);
  entries.push({ name: scene.name, width: img.w, height: img.h, pitch: scene.pitch });
  console.log(
    `${scene.name}.webp  ${img.w}×${img.h}  ${(statSync(out).size / 1024).toFixed(0)} KB  ` +
      `(art pixels of ${scene.pitch} px → ${Math.round(img.w / scene.pitch)}×${Math.round(img.h / scene.pitch)}, grid ${gridScore(img, scene.pitch).toFixed(2)})`,
  );
}

const id = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
writeFileSync(
  join(OUT_DIR, 'scenes.gen.ts'),
  [
    '// GENERATED by scripts/sprites/scene.mjs — do not edit by hand.',
    "// Scene backgrounds as Yeray generated them. width/height in the image's pixels; pitch = image",
    '// pixels per art pixel.',
    ...entries.map((e) => `import ${id(e.name)} from './${e.name}.webp';`),
    '',
    'export type SceneImage = { src: string; width: number; height: number; pitch: number };',
    '',
    'export const SCENE_IMAGES = {',
    ...entries.map((e) => `  ${id(e.name)}: { src: ${id(e.name)}, width: ${e.width}, height: ${e.height}, pitch: ${e.pitch} },`),
    '} satisfies Record<string, SceneImage>;',
    '',
  ].join('\n'),
);
console.log(`→ src/assets/scenes/ (${entries.length} image) + scenes.gen.ts`);
